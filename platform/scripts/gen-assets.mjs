#!/usr/bin/env node
// Bundles the page assets into src/pages/assets.gen.ts so the Worker serves them itself (/assets/*),
// with no Workers Static Assets binding needed (works the same in wrangler dev and the vitest pool).
//   Sources: mockups/assets/{atlas.css, product.css}  (approved Atlas look, single source)
//            src/pages/static/brand/*  (CW mark SVG + PNG fallbacks, favicons, apple-touch icon; vector logo 2026-10-18)
//            src/pages/static/{ssr.css, site.js, og-default.png}                   (SSR-only additions)
// Run after changing any of them:  npm run gen:assets
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const files = [
  ['atlas.css', 'mockups/assets/atlas.css', 'text/css; charset=utf-8'],
  ['product.css', 'mockups/assets/product.css', 'text/css; charset=utf-8'],
  ['ssr.css', 'src/pages/static/ssr.css', 'text/css; charset=utf-8'],
  ['site.js', 'src/pages/static/site.js', 'text/javascript; charset=utf-8'],
  ['handoff.js', 'src/pages/static/handoff.js', 'text/javascript; charset=utf-8'],
  // CW mark: vector logo 2026-10-18 (brand/assets in the journal: cw-mark-light/dark.svg + png-exports). The old
  // /assets/cw-mark-{light,dark}.png URLs keep working and now serve the new mark (256 px PNG fallbacks).
  ['cw-mark-light.svg', 'src/pages/static/brand/cw-mark-light.svg', 'image/svg+xml'],
  ['cw-mark-dark.svg', 'src/pages/static/brand/cw-mark-dark.svg', 'image/svg+xml'],
  ['cw-mark-light.png', 'src/pages/static/brand/cw-mark-light-256.png', 'image/png'],
  ['cw-mark-dark.png', 'src/pages/static/brand/cw-mark-dark-256.png', 'image/png'],
  ['cw-mark-512.png', 'src/pages/static/brand/cw-mark-light-512.png', 'image/png'],
  ['favicon.svg', 'src/pages/static/brand/favicon.svg', 'image/svg+xml'],
  ['favicon.ico', 'src/pages/static/brand/favicon.ico', 'image/x-icon'],
  ['favicon-32.png', 'src/pages/static/brand/favicon-32.png', 'image/png'],
  ['apple-touch-icon.png', 'src/pages/static/brand/apple-touch-icon.png', 'image/png'],
  ['og-default.png', 'src/pages/static/og-default.png', 'image/png'],
];

// Runs before first paint: theme, collapsed sidebar, dismissed announcement (its id is on <html data-ann>).
// Its sha256 goes into the page CSP, so the inline script needs no 'unsafe-inline'.
const BOOT = "(function(){var d=document.documentElement,s;try{s=localStorage}catch(x){s=null}var t=s&&s.getItem('cw-theme');if(t!=='light'&&t!=='dark'){t='light'}d.setAttribute('data-theme',t);if(s&&s.getItem('cw-side')==='off')d.classList.add('cw-side-off');var a=d.getAttribute('data-ann');if(a&&s&&s.getItem('cw-ann-dismissed')===a)d.classList.add('cw-ann-off');})();";

const out = [];
for (const [name, rel, type] of files) {
  const buf = readFileSync(path.join(root, rel));
  const hash = createHash('sha256').update(buf).digest('hex').slice(0, 12);
  const text = type.startsWith('text/');
  out.push(`  ${JSON.stringify(name)}: { type: ${JSON.stringify(type)}, hash: ${JSON.stringify(hash)}, ${text ? 'text' : 'base64'}: ${JSON.stringify(text ? buf.toString('utf8') : buf.toString('base64'))} },`);
}
const bootHash = createHash('sha256').update(BOOT).digest('base64');
writeFileSync(path.join(root, 'src/pages/assets.gen.ts'), `// GENERATED by scripts/gen-assets.mjs — do not edit. Run \`npm run gen:assets\` after changing a source asset.
export interface Asset { type: string; hash: string; text?: string; base64?: string }
export const ASSETS: Record<string, Asset> = {
${out.join('\n')}
};
export const BOOT_SCRIPT = ${JSON.stringify(BOOT)};
export const BOOT_SCRIPT_SHA256 = ${JSON.stringify(bootHash)};
`);
console.log('wrote src/pages/assets.gen.ts', files.map((f) => f[0]).join(', '));
